/** 날짜(YYYY-MM-DD)마다 하나. 같은 날에는 같은 문구. */
export function quoteFor(day: string): string {
  const days = Math.floor(Date.parse(`${day}T00:00:00Z`) / 86_400_000);
  const n = QUOTES.length;
  return QUOTES[((days % n) + n) % n];
}
